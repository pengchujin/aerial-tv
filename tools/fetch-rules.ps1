param(
    # Optional (for example http://127.0.0.1:7890); without it git and curl use the environment.
    [string]$Proxy = '',
    # A commit of Loyalsoldier/clash-rules' release branch; empty = the branch head now.
    [string]$Commit = ''
)
# Refreshes the rule-list snapshot bundled in the APK (app/src/main/assets/proxy/rules): the
# upstream files of one release-branch commit, gzip-compressed and unchanged, plus a manifest
# (commit, fetch time, SHA-256 and size of each upstream file) and the matching NOTICE.txt block.
# reject.txt (ad block) is not bundled: about 1.6 MB even compressed; the TV downloads it when ad
# blocking is first turned on.
$ErrorActionPreference = 'Stop'
$repo = 'Loyalsoldier/clash-rules'
$lists = @('applications', 'private', 'tld-not-cn', 'gfw', 'telegramcidr',
           'icloud', 'apple', 'google', 'proxy', 'direct', 'lancidr', 'cncidr')
$root = Split-Path $PSScriptRoot -Parent
$assets = Join-Path $root 'app/src/main/assets/proxy/rules'
$notice = Join-Path $root 'app/src/main/assets/proxy/NOTICE.txt'
$temp = Join-Path $root 'local/rules-build'
New-Item -ItemType Directory -Force $assets, $temp | Out-Null

if (-not $Commit) {
    $gitArgs = @()
    if ($Proxy) { $gitArgs += @('-c', "http.proxy=$Proxy") }
    $line = & git @gitArgs ls-remote "https://github.com/$repo" refs/heads/release
    if ($LASTEXITCODE -ne 0 -or -not $line) { throw 'Could not read the release branch head' }
    $Commit = ($line -split '\s+')[0]
}
if ($Commit -notmatch '^[0-9a-f]{40}$') { throw "Not a commit id: $Commit" }

$utf8 = New-Object System.Text.UTF8Encoding($false)
$fetchedAt = [DateTimeOffset]::UtcNow
$manifest = @("commit=$Commit", "fetchedAt=$($fetchedAt.ToUnixTimeMilliseconds())")
$rows = @()
try {
    foreach ($name in $lists) {
        $url = "https://raw.githubusercontent.com/$repo/$Commit/$name.txt"
        $raw = Join-Path $temp "$name.txt"
        $curlArgs = @('--fail', '--silent', '--show-error', '--location', '--retry', '2', '--max-time', '180', '--output', $raw)
        if ($Proxy) { $curlArgs += @('--proxy', $Proxy) }
        & curl.exe @curlArgs $url
        if ($LASTEXITCODE -ne 0) { throw "Download failed: $name.txt" }
        $bytes = [IO.File]::ReadAllBytes($raw)
        if ($bytes.Length -lt 16 -or $bytes.Length -gt 8MB) { throw "Unexpected size for $name.txt" }
        $head = [Text.Encoding]::ASCII.GetString($bytes, 0, 8)
        if ($head -ne 'payload:') { throw "$name.txt is not a payload list" }
        $sha = [Security.Cryptography.SHA256]::Create()
        try { $hash = (($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') }) -join '') } finally { $sha.Dispose() }
        $target = Join-Path $assets "$name.txt.gz"
        $out = [IO.File]::Create($target)
        try {
            $gz = New-Object IO.Compression.GzipStream($out, [IO.Compression.CompressionLevel]::Optimal)
            try { $gz.Write($bytes, 0, $bytes.Length) } finally { $gz.Dispose() }
        } finally { $out.Dispose() }
        $manifest += "$name.sha256=$hash"
        $manifest += "$name.bytes=$($bytes.Length)"
        $rows += ('  {0,-17} {1,8} bytes  sha256 {2}' -f "$name.txt", $bytes.Length, $hash)
        Write-Output ("{0}: {1} bytes, gzip {2} bytes" -f $name, $bytes.Length, (Get-Item $target).Length)
    }
} finally { Remove-Item $temp -Recurse -Force -ErrorAction SilentlyContinue }

[IO.File]::WriteAllText((Join-Path $assets 'manifest.properties'), (($manifest -join "`n") + "`n"), $utf8)

$block = @(
    '# BEGIN clash-rules (generated by tools/fetch-rules.ps1)',
    'Rule lists: Loyalsoldier/clash-rules, release branch',
    'Copyright: Loyalsoldier and contributors. License: GNU General Public License, version 3 (see MIHOMO-LICENSE).',
    "Project/source: https://github.com/$repo (lists generated from @Loyalsoldier/v2ray-rules-dat,",
    '@v2fly/domain-list-community, @felixonmars/dnsmasq-china-list, @17mon/china_ip_list, @gfwlist/gfwlist;',
    'see each project for its own terms).',
    "Bundled snapshot: commit $Commit, fetched $($fetchedAt.ToString('yyyy-MM-dd HH:mm')) UTC from",
    "https://raw.githubusercontent.com/$repo/$Commit/<name>.txt, stored unchanged and gzip-compressed",
    'in assets/proxy/rules/<name>.txt.gz. SHA-256 of the upstream files:'
) + $rows + @(
    'reject.txt (ad block) is not bundled; the TV downloads it from the same project when ad blocking is turned on.',
    'At runtime Aerial converts each list to the core''s plain text rule format (one entry per line).',
    '# END clash-rules'
)
$text = [IO.File]::ReadAllText($notice)
$pattern = '(?s)\r?\n?# BEGIN clash-rules.*?# END clash-rules\r?\n?'
$text = [Text.RegularExpressions.Regex]::Replace($text, $pattern, "`n")
$text = $text.TrimEnd() + "`n`n" + ($block -join "`n") + "`n"
[IO.File]::WriteAllText($notice, $text, $utf8)
Write-Output "Snapshot of $repo@$Commit written to $assets"
